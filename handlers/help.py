from aiogram import F, Router
from aiogram.types import CallbackQuery

from keyboards.keyboards import back_to_main_kb

router = Router(name="help")

STAFF_HELP_TEXT = (
    "❓ Как пользоваться ботом\n\n"
    "👔 Выбрать должность — выберите свою профессию (повар, бармен, "
    "официант или уникальную должность вашего заведения, если она есть). "
    "После выбора откроются категории тестов по этой должности.\n\n"
    "📝 Тесты — в каждой категории 5 вопросов, от простых к сложным. "
    "За правильные ответы начисляется опыт (XP), который поднимает ваш "
    "ранг по этой должности (например, у бармена: Барбэк → Бармен → "
    "Миксолог → Бренд-бармен → Сомелье).\n\n"
    "🎓 Сдать экзамен — появляется, если вы прикреплены к заведению "
    "(отправляли /start в его группе). Экзамен — тест на время по самым "
    "сложным вопросам; при успехе вы сразу переходите на следующий ранг. "
    "Код на экзамен можно ввести, если он уже есть, или запросить у "
    "любого администратора заведения прямо на этом экране.\n\n"
    "🏢 Рейтинг заведений — сравнение заведений между собой по среднему "
    "проценту правильных ответов сотрудников.\n\n"
    "👤 Мой профиль — вся ваша статистика в одном месте: ранги по всем "
    "должностям, личный рейтинг среди всех пользователей бота, а если вы "
    "прикреплены к заведению — ещё и место внутри него.\n\n"
    "💼 Вакансии — открытые вакансии в Telegram-канале, и возможность "
    "самому опубликовать объявление.\n\n"
    "🏠 Главное меню — постоянная кнопка под полем ввода: возвращает в "
    "это меню из любого места, сбрасывая незавершённый диалог."
)


@router.callback_query(F.data == "menu:help")
async def cb_help(callback: CallbackQuery) -> None:
    await callback.message.edit_text(STAFF_HELP_TEXT, reply_markup=back_to_main_kb())
    await callback.answer()
