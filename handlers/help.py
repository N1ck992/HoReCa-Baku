    "закончится. Уровни 1-3 открыты всем сразу; уровни 4 и выше "
    "открываются один за другим — для перехода на следующий нужен "
    "хороший результат на предыдущем.\n\n"
    "🎓 Ранг и опыт (XP) начисляются только за общие тесты — те, что "
    "проходятся с главной страницы бота, не привязанные к конкретному "
    "заведению. Тесты внутри заведения на ранг не влияют, у них своя "
    "отдельная статистика.\n\n"
    "🎓 Сдать экзамен — появляется, если вы прикреплены к заведению. Это "
